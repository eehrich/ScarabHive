#: The kit's own icons, drawn in Lucide's grid and stroke. A part styled `fill: var(--pk-icon-pane, none)`
#: fills while the button carrying the icon says it is open (kit.css): the sidebar toggles show whether
#: their side is showing, as an editor's layout buttons do.
CUSTOM = {
    "sidebar-left": '<path d="M5 3h4v18H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2z" style="fill: var(--pk-icon-pane, none); stroke: none" />'
                    '<rect width="18" height="18" x="3" y="3" rx="2" /><path d="M9 3v18" />',
    "sidebar-right": '<path d="M15 3h4a2 2 0 0 1 2 2v14a2 2 0 0 1-2 2h-4z" style="fill: var(--pk-icon-pane, none); stroke: none" />'
                     '<rect width="18" height="18" x="3" y="3" rx="2" /><path d="M15 3v18" />',
    # a window going back into the dock at the right: the way back of picture-in-picture-2
    "dock-in": '<rect width="18" height="18" x="3" y="3" rx="2" /><path d="M15 3v18" /><path d="M6 12h6" />'
               '<path d="m9 9 3 3-3 3" />',
}

_BODY = re.compile(r"<svg[^>]*>(.*)</svg>", re.DOTALL)


def fetch(path: str) -> str:
    with urllib.request.urlopen(f"{SOURCE}/{path}", timeout=30) as response:
        return response.read().decode("utf-8")


def main() -> int:
    symbols = []
    for name in ICONS:
        body = _BODY.search(fetch(f"icons/{name}.svg"))
        if not body:
            print(f"no <svg> body in {name}.svg", file=sys.stderr)
            return 1
        inner = "".join(line.strip() for line in body.group(1).splitlines())
        symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">{inner}</symbol>')
    symbols += [f'<symbol id="{name}" viewBox="0 0 24 24">{inner}</symbol>' for name, inner in CUSTOM.items()]

    sprite = (f"<!-- Lucide {LUCIDE_VERSION} (ISC) and the kit's own, generated by src/scripts/build_icon_sprite.py -->\n"
              '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n")
    (KIT_DIR / "icons.svg").write_text(sprite, encoding="utf-8")
    (KIT_DIR / "LICENSE-lucide.txt").write_text(fetch("LICENSE"), encoding="utf-8")
    print(f"{len(symbols)} icons -> {KIT_DIR / 'icons.svg'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
