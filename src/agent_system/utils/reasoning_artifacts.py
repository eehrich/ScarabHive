"""Invalidation of provider-side reasoning artifacts on history mutation.

THE INVARIANT
=============
``reasoning_details`` blocks that carry a verification payload (OpenAI
encrypted reasoning items, Gemini thought signatures via OpenRouter, Claude
signatures -- see :func:`carries_proof`) are integrity-protected artifacts over
the EXACT conversation history that produced them. Plain reasoning text
(DeepSeek, Kimi) is not, and the rule below leaves it alone:

- OpenAI reasoning models chain their encrypted items — every item is verified
  against the full sequence of prior items ("the entire sequence of consecutive
  reasoning blocks must match the outputs generated by the model during the
  original request", OpenRouter docs). Dropping or altering ANY earlier part
  fails verification: HTTP 400 "The encrypted content for item rs_… could not
  be verified".
- Gemini validates the thought signature of the CURRENT tool-call round-trip.

Therefore: any process that mutates persisted conversation history AFTER
assistant turns were generated — compaction (content swapped for variable
refs), media/tool-result eviction, summarization replacing whole spans —
silently invalidates these artifacts. The failure then surfaces LATER, deep
into a run, when the next LLM call round-trips the now-inconsistent chain.

THE RULE
========
Every code path that mutates history MUST call
:func:`invalidate_reasoning_artifacts` on the message list afterwards.

What it does (provider-agnostic — callers don't know which model runs), for
the artifacts that carry a payload:

1. Strips ``reasoning_details`` (and ``thinking_blocks``, the native Anthropic
   route's carrier of the same thing) from every assistant message EXCEPT the
   most recent one. The most recent may belong to a still-open tool round-trip whose
   Gemini thought signature is REQUIRED on the very next request (stripping it
   risks MALFORMED_FUNCTION_CALL).
2. Flags the most recent assistant message with ``_rd_orphaned: True`` —
   "your predecessors were removed; your chain is broken".

The provider-aware side lives in the LLM client (config-driven
``reasoning_details_mode``, no model-name sniffing):

- ``keep_all``: an ``_rd_orphaned`` message gets its ``reasoning_details``
  (native Anthropic route: its ``thinking_blocks``) stripped per-request
  too — completing a clean chain reset. The model
  re-reasons once; every item generated afterwards forms a fresh, internally
  consistent chain that verifies again.
  That holds for an open tool-use turn as well. Claude models with preserved thinking (Opus, Sonnet, Haiku 5.5, Fable 5.1) bind a thinking
  block to the history it was produced in (system, tools, every earlier
  message): after an edit before it, replaying it is a 400 where Anthropic
  enforces the check, while a tool turn without its thinking is accepted —
  removing blocks from the end is allowed, from the middle it is not.
- ``keep_last`` (Gemini on the chat route): the flag is ignored — the latest
  signature is kept (needed for the open round-trip; older ones were never
  round-tripped anyway). The native Anthropic client drops an orphaned turn's
  blocks in every mode.

``_rd_orphaned`` never reaches a provider: the chat route pops it in its
message post-processing right before the payload is built; the native
Anthropic client builds its payload from named fields and never sends it.
"""

from __future__ import annotations

import logging
from typing import Any, Optional

logger = logging.getLogger(__name__)

#: Flag set on the most recent assistant message when its reasoning-chain
#: predecessors were removed by a history mutation. Read (and honored
#: per reasoning_details_mode) by the LLM client, which also strips the flag
#: from outgoing payloads. No leading underscore: it doubles as a declared
#: pydantic field on ChatMessage (pydantic forbids underscore-prefixed field
#: names), so it survives model_dump / session round-trips.
RD_ORPHANED_FLAG = "rd_orphaned"

#: Format tag of the block in which the Responses route keeps a turn's
#: verbatim output items; no other route can send it.
RESPONSES_ITEMS_FORMAT = "openai-responses-items-v1"


def _get(msg: Any, key: str, default: Any = None) -> Any:
    """Field access that works for both dict messages and message objects."""
    if isinstance(msg, dict):
        return msg.get(key, default)
    return getattr(msg, key, default)


def _pop(msg: Any, key: str) -> Any:
    if isinstance(msg, dict):
        return msg.pop(key, None)
    val = getattr(msg, key, None)
    if val is not None:
        # Objects (e.g. pydantic ChatMessage): set to None instead of delattr.
        # pydantic v2 tolerates delattr but leaves the instance broken — the
        # attribute then raises AttributeError on access instead of returning
        # the field default.
        try:
            setattr(msg, key, None)
        except Exception:
            pass
    return val


def _set(msg: Any, key: str, value: Any) -> None:
    if isinstance(msg, dict):
        msg[key] = value
    else:
        try:
            setattr(msg, key, value)
        except Exception:
            pass  # frozen/slotted message objects: flag is best-effort


def thinking_text_from_details(details: Any) -> str:
    """The readable thinking text carried inside ``reasoning_details``.

    Two shapes exist, and both occur in stored sessions:

    * flat blocks — ``{"type": "reasoning.text", "text": ...}``, and
      ``reasoning.summary`` which keeps its text in ``summary`` instead.
      Streamed fragments are merged per index by the client, so a block
      arriving here is already whole: measured over 95.399 stored sessions,
      separate blocks are separate SECTIONS, each with its own ``**heading**``
      and ending on punctuation — in all 702 multi-block messages at least one
      block ends without trailing whitespace. They are therefore joined like
      paragraphs, not glued: gluing produced
      ``...proper continuity.**Evaluating story inconsistencies**``.
    * a verbatim replay block — ``reasoning.responses_items`` whose ``items``
      are the provider's raw output items; a reasoning item keeps its text in
      ``content[]`` (raw thinking) or ``summary[]`` (condensed).

    ``data`` is never read: that is the encrypted payload for the round-trip,
    not text.

    Accepts a list of blocks or the streaming accumulator (index -> block).
    """
    if isinstance(details, dict):
        details = [details[index] for index in sorted(details)]
    fragments: list[str] = []
    items_texts: list[str] = []
    for block in details or []:
        if not isinstance(block, dict):
            continue
        for item in block.get("items") or ():
            if not isinstance(item, dict) or item.get("type") != "reasoning":
                continue
            for field in ("content", "summary"):
                for part in item.get(field) or ():
                    if (isinstance(part, dict)
                            and isinstance(part.get("text"), str)
                            and part["text"].strip()):
                        items_texts.append(part["text"])
        value = block.get("text") or block.get("summary")
        if isinstance(value, str) and value.strip():
            fragments.append(value)
    return "\n\n".join(fragments + items_texts)


def thinking_text(msg: Any) -> str:
    """The thinking text of one message, wherever it currently lives.

    The text is stored ONCE: on the message as ``reasoning_content`` when the
    provider sent it on its own, or inside ``reasoning_details`` when that
    artifact has to be kept verbatim anyway. Storing both doubled the session
    size of every reasoning run for no gain, so readers ask here instead of
    picking one field.
    """
    own = _get(msg, "reasoning_content")
    if isinstance(own, str) and own.strip():
        return own
    return thinking_text_from_details(_get(msg, "reasoning_details"))


def _keep_thinking_text(msg: Any) -> None:
    """Move the thinking text onto the message before its artifacts are lost.

    Used where the artifact is discarded for a reason that has nothing to do
    with size — a model switch or a chain repair. There the thinking would be
    lost for good, and that is the fallback case worth keeping.

    NOT used by :func:`invalidate_reasoning_artifacts`. That one runs after
    compaction and summarization, which exist BECAUSE the context is too
    large; writing the thinking back would undo part of the very saving they
    just made, permanently and per message (measured over stored sessions:
    median 5.034 characters, p90 11.946, max 373.776). A durable archive for
    reasoning belongs beside the session, not inside it.

    Never overwrites an existing value, and stays silent when there is nothing
    to rescue.
    """
    if _get(msg, "reasoning_content"):
        return
    text = thinking_text_from_details(_get(msg, "reasoning_details"))
    if text:
        _set(msg, "reasoning_content", text)


def strip_reasoning_artifacts_containing(messages: list, item_id: str) -> int:
    """Remove reasoning artifacts of the message(s) carrying block *item_id*.

    Surgical variant of :func:`strip_all_reasoning_artifacts` for the
    "encrypted content for item rs_… could not be verified" 400: the provider
    names ONE defective item — empirically (OpenRouter bridge, assistant turns
    with multiple parallel tool_calls) every OTHER item of the chain still
    verifies once the named one is gone. Dropping only the affected message's
    ``reasoning_details`` preserves the rest of the chain, the prompt cache and
    the model's reasoning continuity.

    The whole ``reasoning_details`` list of a matching message is removed (not
    just the matching block): sibling blocks like ``reasoning.summary`` carry
    no id of their own and are useless without their encrypted twin.

    Works on dicts and message objects. Returns number of messages touched.
    """
    touched = 0
    for msg in messages:
        if _get(msg, "role") != "assistant":
            continue
        blocks = _get(msg, "reasoning_details") or []
        if any(isinstance(b, dict) and b.get("id") == item_id for b in blocks):
            _keep_thinking_text(msg)
            _pop(msg, "reasoning_details")
            _pop(msg, RD_ORPHANED_FLAG)
            touched += 1
    if touched:
        logger.info(
            "Reasoning artifacts stripped from %d message(s) carrying "
            "defective item %s (rest of the chain preserved)",
            touched, item_id,
        )
    return touched


def strip_reasoning_artifacts_served_by(messages: list, backend: str) -> int:
    """Remove the reasoning artifacts of the messages *backend* answered.

    For a refusal after a provider pin was released: the backend that takes
    the retry cannot verify what the released one signed (measured 102 of 102
    refused) and accepts its own (135 of 135). The full reset threw away the
    chain the new backend could still read. Returns number of messages touched.
    """
    touched = 0
    for msg in messages:
        if (_get(msg, "role") == "assistant" and _get(msg, "served_by") == backend
                and _get(msg, "reasoning_details")):
            _keep_thinking_text(msg)
            _pop(msg, "reasoning_details")
            _pop(msg, RD_ORPHANED_FLAG)
            touched += 1
    if touched:
        logger.info("Reasoning artifacts stripped from %d message(s) served by %s "
                    "(the rest of the chain preserved)", touched, backend)
    return touched


def last_served_by(messages: list) -> Optional[str]:
    """The backend that answered the latest assistant turn naming one."""
    for msg in reversed(messages):
        if _get(msg, "role") == "assistant" and _get(msg, "served_by"):
            return _get(msg, "served_by")
    return None


def strip_all_reasoning_artifacts(messages: list) -> int:
    """Remove ALL provider reasoning artifacts from *messages* — full reset.

    Use when the artifacts are invalid beyond the reach of the soft reset in
    :func:`invalidate_reasoning_artifacts` (which keeps the latest message's
    artifact for an open same-model tool round-trip). A model switch is not
    such a case: the clients leave another model's artifacts out per request
    (:func:`produced_by_another_model`).

    - **Poisoned session healing** after a provider rejected the chain
      (HTTP 400 "encrypted content … could not be verified"): stripping only
      the serialized request copy re-triggers the same 400 every turn, because
      the session still carries the broken chain. Strip the ORIGINAL message
      objects so the healing persists with the session.

    Tool calls lose their ``extra_content`` too: native Gemini keeps its thought
    signature there, not in ``reasoning_details``.

    Also clears ``rd_orphaned`` flags where nothing is left to guard. Anthropic
    ``thinking_blocks`` stay: another Claude model takes them back as they are,
    and after a switch back they still belong to the same history -- except
    on an orphaned turn, whose flag therefore
    stays, or its invalidated blocks would travel again.
    Works on dicts and message objects. Returns number of messages touched.
    """
    touched = 0
    for msg in messages:
        if _get(msg, "role") != "assistant":
            continue
        _keep_thinking_text(msg)
        had = _pop(msg, "reasoning_details") is not None
        calls = unsigned_tool_calls(_get(msg, "tool_calls"))
        if calls is not None:
            _set(msg, "tool_calls", calls)
            had = True
        had_flag = (not _get(msg, "thinking_blocks")
                    and _pop(msg, RD_ORPHANED_FLAG) is not None)
        if had or had_flag:
            touched += 1
    if touched:
        logger.info(
            "All reasoning artifacts stripped from %d message(s) "
            "(model switch or poisoned-chain healing; chain restarts fresh)",
            touched,
        )
    return touched


#: What Anthropic's refusal of a thinking block replayed behind an edited
#: history says (lower case): "Invalid `signature` in `thinking` block. The
#: block is bound to a different conversation." The same clause WITHOUT this
#: sentence is a tampered signature, which no strip heals.
BINDING_REFUSAL = "bound to a different conversation"

#: The ``reasoning_details`` format of Claude's thinking on the chat route.
CLAUDE_DETAILS_FORMAT = "anthropic-claude-v1"


def strip_tool_set_bound_reasoning(messages: list) -> int:
    """Remove the reasoning bound to the tool list it was produced under.

    Claude 5.x binds each thinking block to the system prompt and tool list of
    its request (``tool_set_changed``): once a deferred tool joins the list,
    every earlier block is refused on an enforcing account, and silently dropped
    with a changed prefix elsewhere. That is Claude's ``thinking_blocks``
    (native route) and its ``anthropic-claude-v1`` blocks (chat route); other
    providers' reasoning is not bound this way and stays. Their text moves to
    ``reasoning_content``. Returns number of messages touched.
    """
    touched = 0
    for msg in messages:
        if _get(msg, "role") != "assistant":
            continue
        changed = False
        thinking = _get(msg, "thinking_blocks")
        if thinking:
            text = "".join(b.get("thinking") or "" for b in thinking if isinstance(b, dict))
            if text and not _get(msg, "reasoning_content"):
                _set(msg, "reasoning_content", text)
            _pop(msg, "thinking_blocks")
            _pop(msg, "thinking_model")
            changed = True
        blocks = _get(msg, "reasoning_details")
        if blocks:
            keep = [b for b in blocks if not (isinstance(b, dict) and b.get("format") == CLAUDE_DETAILS_FORMAT)]
            if len(keep) != len(blocks):
                _keep_thinking_text(msg)
                if keep:
                    _set(msg, "reasoning_details", keep)
                else:
                    _pop(msg, "reasoning_details")
                changed = True
        touched += changed
    if touched:
        logger.info("Tool-list-bound reasoning stripped from %d message(s) (a tool joined the list)", touched)
    return touched


#: Where a provider puts the signature of a tool call (Gemini's
#: ``extra_content.google.thought_signature``).
TOOL_CALL_SIGNATURE_KEY = "extra_content"


def unsigned_tool_calls(tool_calls: Any) -> Optional[list]:
    """*tool_calls* without their signatures, or ``None`` when none carries one.

    New dicts in a new list: the calls belong to the stored history.
    """
    if not isinstance(tool_calls, list) or not any(
            isinstance(tc, dict) and TOOL_CALL_SIGNATURE_KEY in tc for tc in tool_calls):
        return None
    return [{k: v for k, v in tc.items() if k != TOOL_CALL_SIGNATURE_KEY}
            if isinstance(tc, dict) else tc for tc in tool_calls]


def own_tool_call_signatures_only(d: dict, msg: Any, model: Any) -> None:
    """Drop the tool-call signatures from request dict *d* when another model made *msg*.

    The chat route used to forward native Gemini's signatures to every other
    provider after a switch, and no reset reached them.
    """
    if produced_by_another_model(msg, model):
        calls = unsigned_tool_calls(d.get("tool_calls"))
        if calls is not None:
            d["tool_calls"] = calls


def produced_by_another_model(msg: Any, model: Any) -> bool:
    """Whether *msg*'s reasoning artifacts came, even in part, from a model other than *model*.

    Artifacts are its ``reasoning_details`` and its tool-call signatures; the
    answer is tagged with ``reasoning_model`` when it carries either.

    A client asks this per request and leaves such a message's artifacts out of
    its payload; the stored history keeps them for a switch back. Stripping
    them from the history on every switch lost the first model's chain, and a
    switch back started it again from nothing. A merged message names both
    producers (``a|b``) and is foreign to each. Untagged artifacts are of
    unknown origin and count as the model's own, as before.
    """
    origin = _get(msg, "reasoning_model")
    if not origin or not isinstance(model, str) or not model:
        return False
    return any(part != model for part in str(origin).split("|"))


#: Fields in which a provider hands back a payload it verifies on replay:
#: OpenAI/Gemini ``encrypted_content`` (Responses items), ``data``
#: (``reasoning.encrypted`` blocks), Claude ``signature``.
_PROOF_KEYS = frozenset({"encrypted_content", "data", "signature"})


def carries_proof(artifact: Any) -> bool:
    """Whether a reasoning artifact holds something the provider verifies.

    Only such an artifact is bound to the history it came from. Plain reasoning
    text is not: measured over 3,000 production sessions (05.11.2026), every
    DeepSeek block (4,487) was text only, while GPT, Gemini and Claude blocks
    carried ``encrypted_content`` or ``signature``. Text is just echoed, and
    DeepSeek wants a tool turn's reasoning back. Deciding by shape keeps the
    rule free of model names.
    """
    if isinstance(artifact, dict):
        return any((key in _PROOF_KEYS and isinstance(value, str) and value)
                   or carries_proof(value) for key, value in artifact.items())
    if isinstance(artifact, list):
        return any(carries_proof(value) for value in artifact)
    return False


def _bound_to_history(msg: Any) -> bool:
    return bool(_get(msg, "thinking_blocks")) or carries_proof(_get(msg, "reasoning_details"))


def invalidate_reasoning_artifacts(messages: list, start: int = 0) -> int:
    """Invalidate provider reasoning artifacts after a history mutation.

    Call this AFTER any in-place mutation of persisted conversation history
    (compaction, summarization, eviction). Strips ``reasoning_details`` from
    all assistant messages except the most recent, and flags the most recent
    with ``_rd_orphaned`` so the LLM client can complete the reset for
    chain-based providers (reasoning_details_mode="keep_all").

    Only artifacts that :func:`carries_proof` are touched. Plain reasoning text
    is bound to nothing, so it stays, and the latest turn is not flagged for it.
    Stripping it after every compaction dropped DeepSeek's reasoning, the open
    tool turn's included, and broke the cache from the edit on.

    Works on both dict-shaped messages and message objects.

    Args:
        messages: the (already mutated) conversation history, oldest first.
        start: index of the first message the mutation changed. Assistant
            turns before it came from a history that is unchanged, so their
            artifacts stay — stripping them would rewrite every replayed turn
            and move the prompt-cache break to the front of the conversation.

    Returns:
        Number of messages whose reasoning artifacts were stripped or flagged.
        0 means the history carried no artifact bound to it — nothing to do.
    """
    touched = 0
    last_assistant_idx = -1
    for i, msg in enumerate(messages):
        if _get(msg, "role") == "assistant":
            last_assistant_idx = i

    if last_assistant_idx < 0:
        return 0

    for i, msg in enumerate(messages):
        if i < start or _get(msg, "role") != "assistant" or not _bound_to_history(msg):
            continue
        if i == last_assistant_idx:
            _set(msg, RD_ORPHANED_FLAG, True)
            touched += 1
            continue
        # No rescue here on purpose: this runs after a compaction, whose job
        # is to make the history smaller. See _keep_thinking_text.
        # thinking_blocks are the same artifact on the native Anthropic route:
        # a block is bound to the conversation that produced it, so an edit
        # before it invalidates it just the same.
        had = _pop(msg, "reasoning_details") is not None
        if _pop(msg, "thinking_blocks") is not None:
            _pop(msg, "thinking_model")
            had = True
        if had:
            touched += 1

    if touched:
        logger.info(
            "Reasoning artifacts invalidated after history mutation: "
            "%d message(s) stripped/flagged (chain will rebuild fresh)",
            touched,
        )
    return touched
